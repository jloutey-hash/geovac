K = 2
N_T = 2 * K + 1


def test_pw_orthonormality():
    assert np.max(np.abs(b1.GRAM - np.eye(b1.NW))) < 1e-12


def test_pure_temporal_exact_in_joint():
    Sq = b1.shift_matrix(K, 1)
    L = b1.L_joint(np.kron(np.eye(b1.NW), Sq), K)
    assert abs(L - 2 * np.pi / b1.T_TIME) < 1e-10


def test_pure_spatial_matches_factor_seminorm():
    A = b1.compress_spatial(b1.band_vals(0.5, 0, 0))
    assert abs(b1.L_joint(np.kron(A, np.eye(N_T)), K) - b1.L_spatial(A)) < 1e-10


def test_joint_kernel_condition():
    const = b1.compress_spatial(np.full(b1.NG, 1.7))
    assert b1.L_joint(np.kron(const, np.eye(N_T)), K) < 1e-12
    A = b1.compress_spatial(b1.band_vals(1.0, 1, 1))
    B = b1.shift_matrix(K, 1) + b1.shift_matrix(K, -1)
    assert b1.L_joint(np.kron(A, B), K) > 0.1


def test_leibniz_envelope():
    A = b1.compress_spatial(b1.band_vals(0.5, 0, 0))
    B = b1.shift_matrix(K, 1) + b1.shift_matrix(K, -1)
    Ls, Lt = b1.L_spatial(A), b1.L_temporal(B, K)
    nA, nB = np.linalg.norm(A, 2), np.linalg.norm(B, 2)
    L = b1.L_joint(np.kron(A, B), K)
    assert max(Ls * nB, nA * Lt) - 1e-9 <= L <= Ls * nB + nA * Lt + 1e-9


def test_riemannian_limit_nt1_bit_exact():
    for (j, a, bb) in [(0.5, 0, 0), (1.0, 1, 1)]:
        A = b1.compress_spatial(b1.band_vals(j, a, bb))
        assert abs(b1.L_joint(np.kron(A, np.eye(1)), 0) - b1.L_spatial(A)) < 1e-13


# ---------------------------------------------------------------------------
# Part (iii) defects at the proposition's kernels.  Spatial: Paper 38's central
# Fejer kernel K = |sum_j sqrt(2j+1) chi_j|^2 / Z (def:central_fejer) on the
# j <= 1 window (one spatial cutoff: the driver's Peter-Weyl grid is fixed
# there).  Temporal: the Fejer kernel with K+1 terms, at four cutoffs.  The
# factor bounds themselves hold for ANY probability kernel (triangle
# inequality), so the load-bearing checks are the pairings: each smoothing
# operator must be the one generated by the kernel whose moment it is charged.
# The rate in n_max is NOT exercised here.
# ---------------------------------------------------------------------------

TEMPORAL_KS = (2, 4, 8, 16)
SPATIAL_PANEL = [(0.5, 0, 0), (1.0, 1, 1)]
# Exact band symbols of Paper 38's kernel at n_max = 3 (Z = 6), from the
# Clebsch-Gordan count sum_{j1, j2 -> j} sqrt(d1 d2) / (Z d_j).
P38_SYMBOL = {0.5: (np.sqrt(2) + np.sqrt(6)) / 6, 1.0: (5 + 2 * np.sqrt(3)) / 18}


def _p38_kernel():
    h = sum(np.sqrt(2 * j + 1) * np.einsum("gaa->g", b1.DCACHE[j]) for j in b1.JS)
    K = np.abs(h) ** 2
    K /= float(np.sum(b1.WTS * K))
    dist = np.array([b1.geodesic_dist(*p) for p in b1.PTS])
    return K, float(np.sum(b1.WTS * K * dist))


@pytest.fixture(scope="module")
def _smoothing():
    Ks_vals, gamma_s = _p38_kernel()
    rows = {}
    for key in SPATIAL_PANEL:
        fv = b1.band_vals(*key)
        A = b1.compress_spatial(fv)
        rows[key] = dict(A=A, As=b1.smooth_spatial(A, Ks_vals),
                         lipf=b1.lip_spatial_band(*key), supf=float(np.max(np.abs(fv))))
    return gamma_s, rows


def test_spatial_kernel_is_paper38s(_smoothing):
    """The moment is Paper 38's gamma at n_max = 3 (production sum rule), and the
    smoothing acts on band j as multiplication by that kernel's exact symbol."""
    from geovac.central_fejer_su2 import gamma_n_via_sum_rule
    gamma_s, rows = _smoothing
    assert abs(gamma_s / float(gamma_n_via_sum_rule(3)) - 1) < 2e-3, gamma_s
    for key, r in rows.items():
        A, As = r["A"], r["As"]
        assert np.linalg.norm(As - P38_SYMBOL[key[0]] * A) < 1e-10, key
        defect = np.linalg.norm(As - A, 2)
        assert abs(defect - (1 - P38_SYMBOL[key[0]]) * np.linalg.norm(A, 2)) < 1e-10, key
        assert defect <= gamma_s * r["lipf"], (key, defect, gamma_s * r["lipf"])


def test_temporal_symbol_is_the_charged_kernels(_smoothing):
    """The temporal multiplier is the Fourier symbol of the kernel whose moment
    gamma_t is charged; defect within gamma_t Lip(h); both fall with K."""
    _, rows = _smoothing
    A = rows[SPATIAL_PANEL[0]]["A"]
    T = b1.T_TIME
    for q in (1, 2):
        prev_defect = prev_gamma = np.inf
        for K in TEMPORAL_KS:
            sym, gamma_t = b1.temporal_fejer(K)
            s = np.linspace(0, T, 4000, endpoint=False)
            th = 2 * np.pi * s / T
            F = sum((1 - abs(k) / (K + 1)) * np.cos(k * th) for k in range(-K, K + 1))
            F /= np.mean(F) * T
            assert abs(np.mean(F * np.cos(q * th)) * T - sym[q]) < 1e-10, (K, q)
            assert abs(np.mean(F * np.minimum(s, T - s)) * T - gamma_t) < 1e-3, (K, gamma_t)
            B = b1.shift_matrix(K, q) + b1.shift_matrix(K, -q)
            defect = np.linalg.norm(np.kron(A, sym[q] * B - B), 2)
            liph = 2 * 2 * np.pi * q / T
            assert defect <= gamma_t * np.linalg.norm(A, 2) * liph, (K, q, defect)
            assert defect < prev_defect and gamma_t < prev_gamma, (K, q)
            prev_defect, prev_gamma = defect, gamma_t


def test_product_defect_within_additive_bound(_smoothing):
    """d(Phi_s (x) Phi_t (F), F) <= (gamma_s + gamma_t) Lip_joint(F) on product
    observables F = f (x) 2cos(q theta), at every temporal cutoff."""
    gamma_s, rows = _smoothing
    for K in TEMPORAL_KS:
        sym, gamma_t = b1.temporal_fejer(K)
        for key, r in rows.items():
            for q in (1, 2):
                B = b1.shift_matrix(K, q) + b1.shift_matrix(K, -q)
                liph = 2 * 2 * np.pi * q / b1.T_TIME
                lip_joint = np.hypot(r["lipf"] * 2.0, r["supf"] * liph)
                defect = np.linalg.norm(np.kron(r["As"], sym[q] * B) - np.kron(r["A"], B), 2)
                assert defect <= (gamma_s + gamma_t) * lip_joint, (K, key, q, defect)
