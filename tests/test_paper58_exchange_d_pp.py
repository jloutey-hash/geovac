def _bivariate(r, Fc):
    D = len(Fc)
    A = r.mat(D, D)
    for m, cm in enumerate(Fc):
        if cm == 0:
            continue
        for i in range(m + 1):
            A[i, m - i] = A[i, m - i] + r.c(cm * comb(m, i) * (-1) ** (m - i))
    return A


