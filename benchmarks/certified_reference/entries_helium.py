"""Category 4 -- graph-native helium CI ground-state energies at fixed basis.

WHAT THESE ENTRIES CERTIFY, AND WHAT THEY DO NOT
------------------------------------------------
Each entry is the lowest eigenvalue of the GeoVac graph-native two-electron CI
matrix for helium at a FIXED basis truncation ``n_max``, in the singlet
``M_L = 0`` sector.  They certify the ASSEMBLY -- that this matrix, built from
these integrals, has this eigenvalue -- and nothing about how close that
eigenvalue is to helium.

The physical non-relativistic infinite-mass helium ground state is
``-2.903724377034119598`` Ha (Pekeris / Drake).  The graph-native CI approaches
it slowly from above; at ``n_max = 7`` the corpus headline is 0.19 per cent
(Paper 13).  So an entry below reproducing thirty-five digits of, say,
``-2.8954055606978043...`` is thirty-five certified digits of a number whose
FIRST TWO already differ from helium.  These are fixed-basis reference values
for someone reimplementing the construction, in the same spirit as a published
FCI energy in a stated finite basis -- not accuracy claims.

WHY THE VALUES ARE ALGEBRAIC, AND HOW THEY ARE COMPUTED
-------------------------------------------------------
Every ingredient of the matrix is exact:

  * one-body diagonal ``-Z^2 / (2 n^2)``                          -- rational;
  * one-body off-diagonal ``kappa * (-A_ij) = +1/16`` on graph edges, with
    ``A`` the binary S^3 lattice adjacency and ``kappa = -1/16``  -- rational;
  * radial Slater integrals ``R^k`` at orbital exponent 1, from
    ``geovac.hypergeometric_slater.compute_rk_algebraic``          -- rational;
  * the orbital-exponent scaling ``k_orb = Z``                     -- integer;
  * Gaunt angular coefficients, products of two Wigner 3j symbols  -- each of
    the form ``(rational) * sqrt(rational)``;
  * the spatial-symmetrisation normalisation ``1/sqrt(1)``, ``1/sqrt(2)``,
    ``1/2``                                                        -- algebraic.

So every matrix entry lies in a real field generated by square roots of
rationals, and the ground-state eigenvalue is an ALGEBRAIC NUMBER.  There is no
quadrature anywhere in the route and no convergence question about the matrix:
the only approximation is rounding the algebraic entries to the working
precision, and diagonalising.

This module therefore assembles the matrix in exact arithmetic -- each entry
kept as ``(rational part, {radicand: rational coefficient}, normalisation)`` --
and rounds it to ``mpf`` ONCE, at a chosen working precision.  The ground state
is then obtained by Rayleigh-quotient iteration seeded from a float64
eigenvector.

FOUR INDEPENDENT CHECKS BACK EACH ENTRY
---------------------------------------
1. TWO-PRECISION AGREEMENT.  The whole assemble-and-diagonalise route is run at
   two working precisions (``DPS_LO`` and ``DPS_HI``); the number of leading
   digits on which the two agree is measured and reported.  This is what caps
   the digit claim.
2. A POSTERIORI RESIDUAL BOUND.  For a real symmetric matrix and a normalised
   vector ``v``, ``|lambda_min - v^T H v| <= ||H v - (v^T H v) v||`` -- a
   rigorous bound that does not depend on how the eigenvector was found.  The
   measured residual is reported per entry, together with the matrix-rounding
   perturbation ``n * max|H_ij| * 10^(1-dps)`` that carries it back to the
   exact algebraic matrix.
3. SECOND EIGENSOLVER.  For CI dimensions up to ``LU_CROSSCHECK_MAX_DIM`` the
   same exact matrix is also diagonalised by Rayleigh-quotient iteration with
   full O(n^3) arbitrary-precision LU factorisations -- a different algorithm
   with a different failure mode -- and the two must agree to working
   precision.
4. FLOAT-PIPELINE CROSS-CHECK.  ``geovac.casimir_ci.build_graph_native_fci``
   plus ``numpy.linalg.eigvalsh`` -- the production route, a completely
   separate implementation in float64 -- must reproduce the certified value to
   better than 1e-12.  Its measured agreement is recorded.

A fifth check runs once for the whole category: the 145 hard-coded rational
Slater integrals in ``geovac.casimir_ci._RK4_TABLE`` are re-derived from
``compute_rk_algebraic`` and must match exactly.  That is what rules out a
transcription error in the integral table feeding every entry here.
"""
from __future__ import annotations

import time
from fractions import Fraction
from functools import lru_cache
from math import factorial
from typing import Any, Dict, List, Tuple

import mpmath as mp
import numpy as np

from ._common import agree_digits, entry, frac_str, nstr

#: physical non-relativistic infinite-mass helium ground state (Pekeris/Drake),
#: quoted only so each entry can state honestly how far from helium it is.
#: Kept as a string: mpf() at import time would parse at the default precision.
E_HELIUM_EXACT_STR = "-2.903724377034119598"

#: working precisions for the two-precision certification
DPS_LO = 55
DPS_HI = 75

#: hard cap on the digit claim, regardless of measured agreement
MAX_CLAIM = 35

#: basis truncations to certify.  n_max = 1 is a single configuration and comes
#: out an exact rational; 2..4 are cheap; 5 is the expensive one.
N_MAX_LIST = (1, 2, 3, 4, 5)

#: n_max values whose float-pipeline cross-check is skipped in fast mode
#: (the production float build at n_max = 5 costs ~2 min on its own).
_SLOW_FLOAT_CHECK_FROM = 5


# ---------------------------------------------------------------------------
# exact Wigner 3j:  W = sign * S * sqrt(P), with S, P exact Fractions
# ---------------------------------------------------------------------------
@lru_cache(maxsize=None)
def _w3j_exact(j1: int, j2: int, j3: int,
               m1: int, m2: int, m3: int) -> Tuple[int, Fraction, Fraction]:
    if m1 + m2 + m3 != 0:
        return (0, Fraction(0), Fraction(1))
    if abs(m1) > j1 or abs(m2) > j2 or abs(m3) > j3:
        return (0, Fraction(0), Fraction(1))
    if j3 > j1 + j2 or j3 < abs(j1 - j2):
        return (0, Fraction(0), Fraction(1))
    a, b, c = j1, j2, j3
    tri_num = factorial(a + b - c) * factorial(a - b + c) * factorial(-a + b + c)
    tri_den = factorial(a + b + c + 1)
    P = Fraction(tri_num * factorial(j1 + m1) * factorial(j1 - m1)
                 * factorial(j2 + m2) * factorial(j2 - m2)
                 * factorial(j3 + m3) * factorial(j3 - m3), tri_den)
    t_min = max(0, j2 - j3 - m1, j1 - j3 + m2)
    t_max = min(j1 + j2 - j3, j1 - m1, j2 + m2)
    S = Fraction(0)
    for t in range(t_min, t_max + 1):
        den = (factorial(t) * factorial(j3 - j2 + t + m1)
               * factorial(j3 - j1 + t - m2) * factorial(j1 + j2 - j3 - t)
               * factorial(j1 - t - m1) * factorial(j2 - t + m2))
        S += Fraction((-1) ** t, den)
    # integer phase: (-1) ** negative_int would silently become a float
    sign = -1 if ((j1 - j2 - m3) & 1) else 1
    return (sign, S, P)


@lru_cache(maxsize=None)
def _gaunt_ck_exact(l1: int, m1: int, l2: int, m2: int,
                    k: int) -> Tuple[int, Fraction, Fraction]:
    """Gaunt coefficient as ``sign * C * sqrt(Q)`` with C, Q positive rationals."""
    q = m1 - m2
    s1, S1, P1 = _w3j_exact(l1, k, l2, 0, 0, 0)
    s2, S2, P2 = _w3j_exact(l1, k, l2, -m1, q, m2)
    if s1 == 0 or s2 == 0 or S1 == 0 or S2 == 0:
        return (0, Fraction(0), Fraction(1))
    sign = (-1 if (m1 & 1) else 1) * s1 * s2
    C = S1 * S2
    Q = Fraction((2 * l1 + 1) * (2 * l2 + 1)) * P1 * P2
    if C < 0:
        sign, C = -sign, -C
    return (sign, C, Q)


# ---------------------------------------------------------------------------
# exact radial Slater integrals
# ---------------------------------------------------------------------------
_RK_CACHE: Dict[Tuple[int, ...], Fraction] = {}


def _rk_exact(*key: int) -> Fraction:
    if key not in _RK_CACHE:
        from geovac.hypergeometric_slater import compute_rk_algebraic
        _RK_CACHE[key] = compute_rk_algebraic(*key)
    return _RK_CACHE[key]


def _g_terms_exact(oa, ob, oc, od) -> List[Tuple[Fraction, Fraction]]:
    """<ab|cd> at k_orb = 1 as a list of ``(C, Q)`` -- value = sum C sqrt(Q)."""
    na, la, ma = oa
    nb, lb, mb = ob
    nc, lc, mc = oc
    nd, ld, md = od
    out: List[Tuple[Fraction, Fraction]] = []
    for k in range(max(abs(la - lc), abs(lb - ld)), min(la + lc, lb + ld) + 1):
        if (la + lc + k) % 2 or (lb + ld + k) % 2:
            continue
        sa, Ca, Qa = _gaunt_ck_exact(la, ma, lc, mc, k)
        if sa == 0:
            continue
        sb, Cb, Qb = _gaunt_ck_exact(lb, mb, ld, md, k)
        if sb == 0:
            continue
        R = _rk_exact(na, la, nc, lc, nb, lb, nd, ld, k)
        if R == 0:
            continue
        out.append((sa * sb * Ca * Cb * R, Qa * Qb))
    return out


# ---------------------------------------------------------------------------
# exact assembly of the graph-native CI matrix
# ---------------------------------------------------------------------------
def _orbitals_and_h1(Z: int, n_max: int):
    from geovac.lattice import GeometricLattice
    lat = GeometricLattice(max_n=n_max)
    orbitals = list(lat.states)
    A = lat.adjacency.toarray()
    nz = A[A != 0]
    assert np.all(nz == 1.0), \
        "S^3 lattice adjacency is not binary -- the exact route assumes it is"
    h1: Dict[Tuple[int, int], Fraction] = {}
    for i, (n, _l, _m) in enumerate(orbitals):
        h1[(i, i)] = Fraction(-Z * Z, 2 * n * n)
    n_sp = len(orbitals)
    for i in range(n_sp):
        for j in range(n_sp):
            if i != j and A[i, j] != 0:
                h1[(i, j)] = Fraction(1, 16)      # kappa * (-A_ij), kappa = -1/16
    return orbitals, h1


def _configs(orbitals, m_total: int, spin: str) -> List[Tuple[int, int]]:
    lo = 0 if spin == "singlet" else 1
    return [(i, j)
            for i in range(len(orbitals))
            for j in range(i + lo, len(orbitals))
            if orbitals[i][2] + orbitals[j][2] == m_total]


ExactEntries = Dict[Tuple[int, int], Tuple[Fraction, Dict[Fraction, Fraction], int]]


def build_matrix_exact(Z: int, n_max: int, m_total: int = 0,
                       spin: str = "singlet") -> Tuple[ExactEntries, List]:
    """Assemble the CI matrix with EXACT entries.

    ``entries[(I, J)] = (rat, alg, dnorm)`` encodes
    ``H_IJ = (rat + sum_Q alg[Q] sqrt(Q)) / sqrt(dnorm)``, all rationals exact.
    Mirrors ``geovac.casimir_ci.build_graph_native_fci`` term for term.
    """
    orbitals, h1 = _orbitals_and_h1(Z, n_max)
    cfg = _configs(orbitals, m_total, spin)
    parity = Fraction(1) if spin == "singlet" else Fraction(-1)
    Zf = Fraction(Z)
    entries: ExactEntries = {}
    for I, (i, j) in enumerate(cfg):
        bra = [(i, j, Fraction(1))]
        if i != j:
            bra.append((j, i, parity))
        for J in range(I, len(cfg)):
            p, q = cfg[J]
            ket = [(p, q, Fraction(1))]
            if p != q:
                ket.append((q, p, parity))
            rat = Fraction(0)
            alg: Dict[Fraction, Fraction] = {}
            for a, b, s_bra in bra:
                for c, d, s_ket in ket:
                    s = s_bra * s_ket
                    if b == d and (a, c) in h1:
                        rat += s * h1[(a, c)]
                    if a == c and (b, d) in h1:
                        rat += s * h1[(b, d)]
                    for C, Q in _g_terms_exact(orbitals[a], orbitals[b],
                                               orbitals[c], orbitals[d]):
                        alg[Q] = alg.get(Q, Fraction(0)) + s * C * Zf
            entries[(I, J)] = (rat, {k: v for k, v in alg.items() if v != 0},
                               len(bra) * len(ket))
    return entries, cfg


def realise_mp(entries: ExactEntries, nc: int) -> mp.matrix:
    """Round the exact entries to an ``mp.matrix`` at the CURRENT precision."""
    sqrt_cache: Dict[Fraction, Any] = {}

    def msqrt(Q: Fraction):
        v = sqrt_cache.get(Q)
        if v is None:
            v = mp.sqrt(mp.mpf(Q.numerator) / mp.mpf(Q.denominator))
            sqrt_cache[Q] = v
        return v

    H = mp.matrix(nc, nc)
    for (I, J), (rat, alg, dnorm) in entries.items():
        val = mp.mpf(rat.numerator) / mp.mpf(rat.denominator)
        for Q, C in alg.items():
            val += (mp.mpf(C.numerator) / mp.mpf(C.denominator)) * msqrt(Q)
        if dnorm == 2:
            val /= mp.sqrt(2)
        elif dnorm == 4:
            val /= 2
        H[I, J] = val
        H[J, I] = val
    return H


def _norm(x):
    return mp.sqrt(sum(xi ** 2 for xi in x))


def ground_state_mp_lu(H: mp.matrix, max_it: int = 12):
    """Lowest eigenvalue by Rayleigh-quotient iteration with exact LU solves.

    Straightforward and slow: each iteration costs an O(n^3) arbitrary-precision
    LU factorisation.  Kept as the reference implementation that
    ``ground_state_mp`` is checked against at small n.
    """
    n = H.rows
    Hf = np.array([[float(H[i, j]) for j in range(n)] for i in range(n)])
    w, V = np.linalg.eigh(Hf)
    v = mp.matrix([mp.mpf(float(x)) for x in V[:, 0]])
    v = v / _norm(v)
    lam = (v.T * (H * v))[0]
    prev = None
    for _ in range(max_it):
        try:
            x = mp.lu_solve(H - lam * mp.eye(n), v)
        except Exception:      # near-singular shift: lam is already converged
            break
        v = x / _norm(x)
        lam = (v.T * (H * v))[0]
        if prev is not None and lam == prev:
            break
        prev = lam
    return lam, _norm(H * v - lam * v), float(w[0])


def ground_state_mp(H: mp.matrix, max_it: int = 40):
    """Lowest eigenvalue by float64-preconditioned residual refinement.

    Same fixed point as inverse iteration, but the correction equation
    ``(H - lambda) delta = -r,  delta orthogonal to v`` is solved in the FLOAT64
    eigenbasis of H rather than by an arbitrary-precision factorisation:

        delta = - sum_{k != 0} (u_k^T r) / (w_k - lambda) * u_k

    with ``(w_k, u_k)`` the float64 eigenpairs.  Only matrix-vector products are
    done at working precision, so an iteration is O(n^2) instead of O(n^3), and
    the float64 eigenbasis being inexact costs convergence RATE, never
    correctness: the returned residual ``||H v - lambda v||`` is a rigorous a
    posteriori bound on ``|lambda - lambda_min|`` for symmetric H whatever the
    iterate is.

    Returns ``(lambda, residual, float64_seed_eigenvalue)``.
    """
    n = H.rows
    Hf = np.array([[float(H[i, j]) for j in range(n)] for i in range(n)])
    w, V = np.linalg.eigh(Hf)
    Vm = mp.matrix(n, n)
    for i in range(n):
        for j in range(n):
            Vm[i, j] = mp.mpf(float(V[i, j]))
    wm = [mp.mpf(float(x)) for x in w]

    v = mp.matrix([Vm[i, 0] for i in range(n)])
    v = v / _norm(v)
    lam = (v.T * (H * v))[0]
    r = H * v - lam * v
    rn = _norm(r)
    for _ in range(max_it):
        c = Vm.T * r
        delta = mp.matrix(n, 1)
        for k in range(1, n):
            den = wm[k] - lam
            if den == 0:
                continue
            delta[k] = -c[k] / den
        v = v + Vm * delta
        v = v / _norm(v)
        lam = (v.T * (H * v))[0]
        r = H * v - lam * v
        new_rn = _norm(r)
        if new_rn == 0 or new_rn > rn / 2:     # converged, or stagnating
            rn = min(rn, new_rn)
            break
        rn = new_rn
    return lam, rn, float(w[0])


# ---------------------------------------------------------------------------
# certification of one n_max
# ---------------------------------------------------------------------------
#: dimension below which the slow O(n^3) LU eigensolver is also run, as an
#: independent second high-precision eigensolver on the same matrix
LU_CROSSCHECK_MAX_DIM = 120


def certify(n_max: int, Z: int = 2, dps_lo: int = DPS_LO,
            dps_hi: int = DPS_HI, lu_check: bool = True) -> Dict[str, Any]:
    """Assemble exactly, diagonalise at two precisions, report the evidence."""
    t0 = time.time()
    entries, cfg = build_matrix_exact(Z, n_max)
    nc = len(cfg)
    out: Dict[str, Any] = {"n_max": n_max, "dim": nc,
                           "assembly_seconds": round(time.time() - t0, 1)}

    vals = {}
    for dps in (dps_lo, dps_hi):
        with mp.workdps(dps):
            H = realise_mp(entries, nc)
            lam, resid, lam_f = ground_state_mp(H)
            hmax = max(abs(H[i, j]) for i in range(nc) for j in range(nc))
            vals[dps] = (mp.mpf(lam), mp.mpf(resid), lam_f,
                         mp.mpf(nc) * hmax * mp.mpf(10) ** (1 - dps))
            if dps == dps_hi and lu_check and nc <= LU_CROSSCHECK_MAX_DIM:
                lam_lu, _resid_lu, _seed = ground_state_mp_lu(H)
                out["lu_agree_digits"] = min(agree_digits(lam, lam_lu), dps)

    with mp.workdps(dps_hi + 20):
        # cap at dps_lo: two routes cannot evidence more digits than the
        # coarser of them carries (agree_digits returns a sentinel if equal)
        agree = min(agree_digits(vals[dps_lo][0], vals[dps_hi][0]), dps_lo)
        out["agree_digits"] = agree
        out["claim"] = min(MAX_CLAIM, agree)
        out["value_mp"] = +vals[dps_hi][0]
        out["value_str"] = nstr(vals[dps_hi][0], out["claim"])
        out["residual"] = nstr(vals[dps_hi][1], 3)
        out["rounding_bound"] = nstr(vals[dps_lo][3], 3)
        out["float64_seed"] = vals[dps_hi][2]
        out["pct_above_helium"] = nstr(
            abs((vals[dps_hi][0] - mp.mpf(E_HELIUM_EXACT_STR))
                / mp.mpf(E_HELIUM_EXACT_STR)) * 100, 3)
    return out


def _exact_rational_ground_state(Z: int) -> Fraction:
    """n_max = 1: one configuration (1s^2), so the energy is a rational.

    ``E = 2 * (-Z^2/2) + Z * R^0(1s1s,1s1s) = -Z^2 + 5Z/8``.
    """
    entries, cfg = build_matrix_exact(Z, 1)
    assert len(cfg) == 1, "n_max = 1 should give a single configuration"
    rat, alg, dnorm = entries[(0, 0)]
    assert dnorm == 1
    val = rat
    for Q, C in alg.items():
        assert Q == 1, f"n_max = 1 entry carries an irrational sqrt({Q})"
        val += C
    return val


# ---------------------------------------------------------------------------
# float-pipeline cross-check (the production route)
# ---------------------------------------------------------------------------
def _float_pipeline(n_max: int, Z: int = 2) -> float:
    from geovac.casimir_ci import build_graph_native_fci
    H = build_graph_native_fci(Z=Z, n_max=n_max, m_total=0, spin="singlet")
    return float(np.linalg.eigvalsh(H)[0])


def _slater_table_crosscheck() -> Tuple[int, int]:
    """Re-derive every hard-coded rational in casimir_ci._RK4_TABLE."""
    from geovac.casimir_ci import _RK4_TABLE
    from geovac.hypergeometric_slater import compute_rk_algebraic
    bad = 0
    for key, val in _RK4_TABLE.items():
        if compute_rk_algebraic(*key) != val:
            bad += 1
    return len(_RK4_TABLE), bad


