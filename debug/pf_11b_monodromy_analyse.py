"""PF1, PF3, PF4: analysis of the pf_11_monodromy.py run.  Monodromy matrices of L at the base point B (unit Taylor
data, rescaled by rho^k), M_0 directly and M_x0 = P^-1 C P from the vectors before (P) and after (C P) each circle.
The action on ker L / ker R (R = chain_R7, the exact order-7 right divisor; R_6 for the planted control) through
Q: f -> the first ord(L) - ord(R) Taylor coefficients of R f at B.  Burnside: the quotient is irreducible over C(x)
iff the algebra generated by its matrices is all of M_n(C).
Controls: M = I at the ordinary points 25/4 and 10; the invariance residual |Q M - N Q|; the planted split (the 13-dim
quotient by R_6 contains the invariant line ker R_7 / ker R_6, so its algebra must be proper); local eigenvalues
against the exponents; the loop around infinity.
usage: python pf_11b_monodromy_analyse.py <tag> [dps]"""
from __future__ import annotations
import json, sys, time
from pathlib import Path
import mpmath as mp
import numpy as np
sys.path.insert(0, str(Path(__file__).parent))
import correlated_triangle_g32_lib as G

DATA = Path(__file__).parent / "data"
tag = sys.argv[1]
rec = json.loads((DATA / f"pf_11_monodromy_{tag}.json").read_text())
mp.mp.dps = int(sys.argv[2]) if len(sys.argv) > 2 else rec["dps"]
R = rec["order"]
cols = rec["columns"]
B = mp.mpc("0.12", "0.12")
RHO = mp.mpf("0.1")
GEN = ["0", "1/4", "1", "9/4", "4", "9", "49/4", "16", "81/4"]
CTRL = ["25/4", "10"]
out = {"dps": mp.mp.dps, "base": rec["base"], "rho": str(RHO)}


def dec(v):
    return [mp.mpc(a, b) for a, b in v]


def mat(colvecs):
    n = len(colvecs)
    M = mp.matrix(len(colvecs[0]), n)
    for j, v in enumerate(colvecs):
        for i, z in enumerate(v):
            M[i, j] = z
    return M


def fro(A):
    return mp.sqrt(mp.fsum(abs(A[i, j]) ** 2 for i in range(A.rows) for j in range(A.cols)))


def eye(n):
    return mp.eye(n)


S = mp.diag([RHO ** k for k in range(R)])
Si = mp.diag([RHO ** (-k) for k in range(R)])
Ms = {}
Ms["0"] = S * mat([dec(cols[str(i)]["0"]) for i in range(R)]) * Si
for s in GEN[1:] + CTRL:
    P = mat([dec(cols[str(i)][s]["top"]) for i in range(R)])
    CP = mat([dec(cols[str(i)][s]["after"]) for i in range(R)])
    Ms[s] = S * (mp.inverse(P) * CP) * Si

out["controls_|M-I|"] = {s: mp.nstr(fro(Ms[s] - eye(R)), 4) for s in CTRL}
print("controls |M - I| (ordinary points):", out["controls_|M-I|"], flush=True)
out["local_sv_19"] = {}
for s in GEN:
    sv = mp.svd_c(Ms[s] - eye(R), compute_uv=False)
    svs = sorted([abs(v) for v in sv], reverse=True)
    out["local_sv_19"][s] = [mp.nstr(v, 3) for v in svs[:5]]
    print(f"M_{s} - I, top singular values:", out["local_sv_19"][s], flush=True)


def Qmat(Rop):
    """Q[m, n]: Taylor coefficient m of R f at B in terms of the Taylor coefficients a_n of f (unscaled)."""
    A = G.dform(G.shift_theta(Rop, 3))
    r = len(A) - 1
    k = R - r
    Q = mp.matrix(k, R)
    sh = []
    for j in range(r + 1):
        c = [mp.mpc(int(v)) for v in A[j].coeffs()] or [mp.mpc(0)]
        n = len(c)
        for kk in range(n):
            for jj in range(n - 2, kk - 1, -1):
                c[jj] += B * c[jj + 1]
        sh.append(c)
    for m in range(k):
        for j in range(r + 1):
            for l in range(min(m, len(sh[j]) - 1) + 1):
                n = m - l + j
                Q[m, n] += sh[j][l] * mp.ff(n, j)
    return Q


def quotient(Rop, name):
    Q = Qmat(Rop) * Si
    Q = mp.diag([RHO ** m for m in range(Q.rows)]) * Q
    Q = Q / fro(Q)
    Qp = Q.H * mp.inverse(Q * Q.H)
    Ns, inv = {}, {}
    for s in GEN + CTRL:
        N = Q * Ms[s] * Qp
        inv[s] = mp.nstr(fro(Q * Ms[s] - N * Q) / fro(Q * Ms[s]), 3)
        Ns[s] = N
    print(f"{name}: invariance residual |Q M - N Q| / |Q M|:", inv, flush=True)
    return Ns, inv


def algdim(gens, n, tol):
    basis = []
    acc, rej = [], []

    def vec(X):
        return [X[i, j] for i in range(n) for j in range(n)]

    def add(X):
        v = vec(X)
        nv = mp.sqrt(mp.fsum(abs(z) ** 2 for z in v))
        w = v
        for _ in range(2):
            for b in basis:
                c = mp.fdot(b, w, conjugate=True)
                w = [wi - c * bi for wi, bi in zip(w, b)]
        nw = mp.sqrt(mp.fsum(abs(z) ** 2 for z in w))
        res = nw / nv
        if res > tol:
            basis.append([z / nw for z in w])
            acc.append(res)
            return True
        rej.append(res)
        return False

    gens = [g / fro(g) for g in gens]
    queue = [eye(n)]
    add(queue[0])
    i = 0
    while i < len(queue) and len(basis) < n * n:
        X = queue[i]
        i += 1
        for g in gens:
            Y = g * X
            Y = Y / fro(Y)
            if add(Y):
                queue.append(Y)
            if len(basis) == n * n:
                break
    return len(basis), (mp.nstr(min(acc), 3) if acc else None), (mp.nstr(max(rej), 3) if rej else None)


pieces = json.loads((DATA / "pf_pieces_tetra_exact.json").read_text())
TOL = mp.mpf(10) ** (-20)
for key, name in (("chain_R7", "F_8 (ker L / ker R_7)"), ("chain_R6", "planted: ker L / ker R_6")):
    Rop = G.parse_op(pieces[key])
    Ns, inv = quotient(Rop, name)
    n = R - (len(Rop) - 1)
    t0 = time.time()
    dim, amin, rmax = algdim([Ns[s] for s in GEN], n, TOL)
    print(f"{name}: algebra dimension {dim} of {n*n}; smallest accepted residual {amin}, largest rejected {rmax} "
          f"({time.time()-t0:.0f}s)", flush=True)
    ent = {"n": n, "invariance": inv, "algebra_dim": dim, "full": n * n, "min_accepted": amin, "max_rejected": rmax,
           "controls_|N-I|": {s: mp.nstr(fro(Ns[s] - eye(n)), 3) for s in CTRL}}
    ent["eigs"] = {}
    for s in GEN:
        ev = mp.eig(Ns[s], left=False, right=False)
        ent["eigs"][s] = sorted([mp.nstr(mp.chop(z, 1e-15), 4) for z in ev])
    prod = eye(n)
    for s in GEN:
        prod = Ns[s] * prod
    ent["infinity_eigs_order_0_first"] = sorted([mp.nstr(mp.chop(z, 1e-15), 4) for z in mp.eig(prod, left=False, right=False)])
    prod = eye(n)
    for s in GEN[::-1]:
        prod = Ns[s] * prod
    ent["infinity_eigs_reverse"] = sorted([mp.nstr(mp.chop(z, 1e-15), 4) for z in mp.eig(prod, left=False, right=False)])
    print(f"{name}: eigenvalues", ent["eigs"], flush=True)
    print(f"{name}: product, both orders", ent["infinity_eigs_order_0_first"], ent["infinity_eigs_reverse"], flush=True)
    if key == "chain_R7":
        # reading, not scored: an invariant bilinear form up to a sign character (chi = 1 at the unipotent and t = 0
        # points, chi = +-1 at x = 1 and x = 9), float64 after the rescaling
        A = {s: np.array([[complex(Ns[s][i, j]) for j in range(n)] for i in range(n)]) for s in GEN}
        forms = {}
        for c1 in (1, -1):
            for c9 in (1, -1):
                chi = {s: 1 for s in GEN}
                chi["1"], chi["9"] = c1, c9
                K = np.vstack([np.kron(A[s].T, A[s].T) - chi[s] * np.eye(n * n) for s in GEN])
                _, sv, Vh = np.linalg.svd(K)
                Gm = Vh[-1].conj().reshape(n, n, order="F")
                sym = np.linalg.norm(Gm - Gm.T) / np.linalg.norm(Gm)
                asym = np.linalg.norm(Gm + Gm.T) / np.linalg.norm(Gm)
                forms[f"chi(1)={c1}, chi(9)={c9}"] = {"smallest_sv": [f"{v:.2e}" for v in sv[-3:]],
                                                     "|G-G^T|/|G|": f"{sym:.2e}", "|G+G^T|/|G|": f"{asym:.2e}"}
        ent["bilinear_form_reading"] = forms
        print("invariant form (reading):", forms, flush=True)
    out[key] = ent


def orbit_dim(gens, y, tol):
    """dimension of the span of the monodromy orbit of y (the solution space of Y's minimal annihilator)"""
    basis, acc, rej = [], [], []

    def add(v):
        nv = mp.sqrt(mp.fsum(abs(z) ** 2 for z in v))
        w = list(v)
        for _ in range(2):
            for b in basis:
                c = mp.fdot(b, w, conjugate=True)
                w = [wi - c * bi for wi, bi in zip(w, b)]
        nw = mp.sqrt(mp.fsum(abs(z) ** 2 for z in w))
        if nw / nv > tol:
            basis.append([z / nw for z in w])
            acc.append(nw / nv)
            return True
        rej.append(nw / nv)
        return False

    queue = [list(y)]
    add(queue[0])
    i = 0
    while i < len(queue) and len(basis) < len(y):
        v = queue[i]
        i += 1
        for g in gens:
            u = g * mp.matrix(v)
            u = [u[k] for k in range(len(y))]
            if add(u):
                queue.append(u)
    return len(basis), (mp.nstr(min(acc), 3) if acc else None), (mp.nstr(max(rej), 3) if rej else None)


