rec = json.loads((DATA / f"pf_11_monodromy_{tag}.json").read_text())
mp.mp.dps = int(sys.argv[2]) if len(sys.argv) > 2 else rec["dps"]
R = rec["order"]
cols = rec["columns"]
B = mp.mpc("0.12", "0.12")
RHO = mp.mpf("0.1")
GEN = ["0", "1/4", "1", "9/4", "4", "9", "49/4", "16", "81/4"]
CTRL = ["25/4", "10"]
out = {"dps": mp.mp.dps, "base": rec["base"], "rho": str(RHO)}


def dec(v):
    return [mp.mpc(a, b) for a, b in v]


def mat(colvecs):
    n = len(colvecs)
    M = mp.matrix(len(colvecs[0]), n)
    for j, v in enumerate(colvecs):
        for i, z in enumerate(v):
            M[i, j] = z
    return M


def fro(A):
    return mp.sqrt(mp.fsum(abs(A[i, j]) ** 2 for i in range(A.rows) for j in range(A.cols)))


def eye(n):
    return mp.eye(n)


S = mp.diag([RHO ** k for k in range(R)])
Si = mp.diag([RHO ** (-k) for k in range(R)])
Ms = {}
Ms["0"] = S * mat([dec(cols[str(i)]["0"]) for i in range(R)]) * Si
for s in GEN[1:] + CTRL:
    P = mat([dec(cols[str(i)][s]["top"]) for i in range(R)])
    CP = mat([dec(cols[str(i)][s]["after"]) for i in range(R)])
    Ms[s] = S * (mp.inverse(P) * CP) * Si

out["controls_|M-I|"] = {s: mp.nstr(fro(Ms[s] - eye(R)), 4) for s in CTRL}
print("controls |M - I| (ordinary points):", out["controls_|M-I|"], flush=True)
out["local_sv_19"] = {}
for s in GEN:
    sv = mp.svd_c(Ms[s] - eye(R), compute_uv=False)
    svs = sorted([abs(v) for v in sv], reverse=True)
    out["local_sv_19"][s] = [mp.nstr(v, 3) for v in svs[:5]]
    print(f"M_{s} - I, top singular values:", out["local_sv_19"][s], flush=True)


def Qmat(Rop):
    """Q[m, n]: Taylor coefficient m of R f at B in terms of the Taylor coefficients a_n of f (unscaled)."""
    A = G.dform(G.shift_theta(Rop, 3))
    r = len(A) - 1
    k = R - r
    Q = mp.matrix(k, R)
    sh = []
    for j in range(r + 1):
        c = [mp.mpc(int(v)) for v in A[j].coeffs()] or [mp.mpc(0)]
        n = len(c)
        for kk in range(n):
            for jj in range(n - 2, kk - 1, -1):
                c[jj] += B * c[jj + 1]
        sh.append(c)
    for m in range(k):
        for j in range(r + 1):
            for l in range(min(m, len(sh[j]) - 1) + 1):
                n = m - l + j
                Q[m, n] += sh[j][l] * mp.ff(n, j)
    return Q


def quotient(Rop, name):
    Q = Qmat(Rop) * Si
    Q = mp.diag([RHO ** m for m in range(Q.rows)]) * Q
    Q = Q / fro(Q)
    Qp = Q.H * mp.inverse(Q * Q.H)
    Ns, inv = {}, {}
    for s in GEN + CTRL:
        N = Q * Ms[s] * Qp
        inv[s] = mp.nstr(fro(Q * Ms[s] - N * Q) / fro(Q * Ms[s]), 3)
        Ns[s] = N
    print(f"{name}: invariance residual |Q M - N Q| / |Q M|:", inv, flush=True)
    return Ns, inv


def algdim(gens, n, tol):
    basis = []
    acc, rej = [], []

    def vec(X):
        return [X[i, j] for i in range(n) for j in range(n)]

    def add(X):
        v = vec(X)
        nv = mp.sqrt(mp.fsum(abs(z) ** 2 for z in v))
        w = v
        for _ in range(2):
            for b in basis:
                c = mp.fdot(b, w, conjugate=True)
                w = [wi - c * bi for wi, bi in zip(w, b)]
        nw = mp.sqrt(mp.fsum(abs(z) ** 2 for z in w))
        res = nw / nv
        if res > tol:
            basis.append([z / nw for z in w])
            acc.append(res)
            return True
        rej.append(res)
        return False

    gens = [g / fro(g) for g in gens]
    queue = [eye(n)]
    add(queue[0])
    i = 0
    while i < len(queue) and len(basis) < n * n:
        X = queue[i]
        i += 1
        for g in gens:
            Y = g * X
            Y = Y / fro(Y)
            if add(Y):
                queue.append(Y)
            if len(basis) == n * n:
                break
    return len(basis), (mp.nstr(min(acc), 3) if acc else None), (mp.nstr(max(rej), 3) if rej else None)


def balance(gens, iters=60):
    n = gens[0].rows
    g = [A.copy() for A in gens]
    d = [mp.mpf(1)] * n
    for _ in range(iters):
        for i in range(n):
            r = mp.fsum(abs(A[i, k]) for A in g for k in range(n) if k != i)
            c = mp.fsum(abs(A[k, i]) for A in g for k in range(n) if k != i)
            if r == 0 or c == 0:
                continue
            f = mp.sqrt(c / r)
            d[i] *= f
            for A in g:
                for k in range(n):
                    A[i, k] *= f
                    A[k, i] /= f
    return g, d


# Norton's irreducibility test.  Z = X - lam I with X a random element of the algebra and lam a simple eigenvalue of X,
# so ker Z = <v> and ker Z^T = <u>.  If the submodule generated by v is all of V and the dual submodule generated by u
# is all of V*, V is irreducible.  The submodule generated by a vector is the span of all words applied to it; here
# words up to length 3 in the generators (and the identity), stacked and normalised, with the rank read from the
# singular values.  Planted control: the 13-dim quotient by R_6 has an invariant line, so for some lam the orbit of v
# or of u is not full.
import random


def words(gens, maxlen):
    n = gens[0].rows
    ws = [eye(n)]
    layer = [eye(n)]
    for _ in range(maxlen):
        nxt = []
        for W in layer:
            for A in gens:
                Y = A * W
                nxt.append(Y / fro(Y))
        ws += nxt
        layer = nxt
    return ws


def span_sv(ws, v):
    n = len(v)
    cols = []
    for W in ws:
        u = W * mp.matrix(v)
        nu = mp.sqrt(mp.fsum(abs(u[k]) ** 2 for k in range(n)))
        cols.append([u[k] / nu for k in range(n)])
    M = mp.matrix(n, len(cols))
    for j, c in enumerate(cols):
        for k in range(n):
            M[k, j] = c[k]
    sv = mp.svd_c(M, compute_uv=False)
    return sorted([abs(s) for s in sv], reverse=True)


def norton(gens, label, ntrials=3, seed=20261025):
    rnd = random.Random(seed)
    n = gens[0].rows
    ws = words(gens, 3)
    wsT = [W.T for W in ws]
    res = []
    for trial in range(ntrials):
        X = mp.matrix(n, n)
        for W in ws[: 1 + len(gens) + len(gens) ** 2]:
            X += mp.mpc(rnd.gauss(0, 1), rnd.gauss(0, 1)) * W
        E, ER = mp.eig(X)
        EL = mp.inverse(ER).T
        for k in range(n):
            lam = E[k]
            gap = min(abs(lam - E[j]) for j in range(n) if j != k) / max(abs(z) for z in E)
            v = [ER[i, k] for i in range(n)]
            u = [EL[i, k] for i in range(n)]
            sv = span_sv(ws, v)
            svT = span_sv(wsT, u)
            res.append({"trial": trial, "eig": k, "sep": mp.nstr(gap, 3),
                        "orbit_sv_tail": [mp.nstr(s, 3) for s in sv[-3:]], "orbit_sv_top": mp.nstr(sv[0], 3),
                        "dual_sv_tail": [mp.nstr(s, 3) for s in svT[-3:]],
                        "orbit_min": sv[-1], "dual_min": svT[-1]})
    mins = sorted(r["orbit_min"] for r in res)
    dmins = sorted(r["dual_min"] for r in res)
    print(f"{label}: smallest orbit singular value over {len(res)} null vectors: {mp.nstr(mins[0], 3)} "
          f"(next {mp.nstr(mins[1], 3)}, median {mp.nstr(mins[len(mins)//2], 3)}); dual: {mp.nstr(dmins[0], 3)} "
          f"(next {mp.nstr(dmins[1], 3)}, median {mp.nstr(dmins[len(dmins)//2], 3)})", flush=True)
    for r in res:
        r["orbit_min"] = mp.nstr(r["orbit_min"], 3)
        r["dual_min"] = mp.nstr(r["dual_min"], 3)
    return res


