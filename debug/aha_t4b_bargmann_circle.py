def has_linear_recurrence(coeffs, max_order):
    """Exact over Q: do the coefficients obey a constant-coefficient linear
    recurrence of order <= max_order? (<=> rational generating function)."""
    for r in range(1, max_order + 1):
        rows, rhs = [], []
        for k in range(r, len(coeffs)):
            rows.append([sp.Rational(coeffs[k - 1 - i]) for i in range(r)])
            rhs.append(sp.Rational(coeffs[k]))
        A = sp.Matrix(rows)
        b = sp.Matrix(rhs)
        if A.rank() == A.row_join(b).rank():
            return True, r
    return False, None


