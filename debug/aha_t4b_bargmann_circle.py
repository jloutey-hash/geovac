def Zminus_hurwitz(sv, sh):
    """generic shift: g_N = [x^2 + (3-2sh) x + (sh-1)(sh-2)]/2 with x = N + sh."""
    def etaH(s2):
        return mp.mpf(2) ** (-s2) * (mp.zeta(s2, sh / 2) - mp.zeta(s2, (sh + 1) / 2))
    A = mp.mpf(1) / 2
    B = (3 - 2 * sh) / 2
    C = (sh - 1) * (sh - 2) / 2
    return A * etaH(sv - 2) + B * etaH(sv - 1) + C * etaH(sv)


