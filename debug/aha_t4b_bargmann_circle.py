def beta_dirichlet(sv):
    """beta(s) = L(s, chi_-4) via Hurwitz: 4^-s [zeta(s,1/4) - zeta(s,3/4)]."""
    return (mp.zeta(sv, mp.mpf(1) / 4) - mp.zeta(sv, mp.mpf(3) / 4)) / mp.mpf(4) ** sv


def alt_sum(term, n_terms=400, levels=None):
    """Sum_{N>=0} (-1)^N term(N) by the Euler (repeated-averaging) transform.

    Hand-written: no library acceleration, no logs in the summand (power terms
    only), so the memory-rule Levin/log trap does not apply.  Validated by
    running at two (n_terms, levels) settings and two precisions."""
    if levels is None:
        levels = n_terms // 2
    partial = []
    s = mp.mpf(0)
    for n in range(n_terms):
        s += (-1) ** n * term(n)
        partial.append(s)
    row = partial[-(levels + 1):]
    for _ in range(levels):
        row = [(row[i] + row[i + 1]) / 2 for i in range(len(row) - 1)]
    return row[0]


