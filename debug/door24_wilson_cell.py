"""Door 24 Wilson-gauge cell (docs/atlas.md): which SU(2) inside so(4) does a finite nucleus leave standing,
and is it the one the "S^3 = SU(2)" reading of Paper 30 singles out?

so(4) = su(2)_+ (+) su(2)_-, J^(+-) = (L +- A)/2.  The chiral factors are left / right multiplication of
S^3 = SU(2) on itself (free, transitive); the diagonal SO(3), generated by L = J^+ + J^-, is conjugation
(fixed points +-1).  Paper 25's Hopf fibre generator L_z + A_z = 2 J^+_z is the torus of su(2)_+, and Paper 30
Prop. (maximal-torus reduction) makes Paper 25 the Cartan sector of its SU(2): so the SU(2) consistent with both
papers is su(2)_+ (the mirror convention gives su(2)_-; both are tested).

Computes, hydrogenic Z = 1, n <= NMAX (generators block-diagonal in n, so the truncation is exact):
  1. so(4) and the chiral split close: [J+,J-] = 0, each closes su(2), J+^2 = J-^2 = (n^2-1)/4.
  2. commutant of the door-24 correction V (uniform sphere R = 0.05, the guard's operator) in so(4),
     and its intersection with su(2)_+ and su(2)_-.
  3. relative commutators ||[V, X]|| / ||V|| for X = L_a, J+_a, J-_a, A_a.
  4. label shadow of free vs fixed points: invariant vectors of each subgroup per shell.

Run: OMP_NUM_THREADS=1 python debug/door24_wilson_cell.py
"""
from __future__ import annotations

from math import factorial, sqrt
from typing import List, Tuple

import numpy as np
from scipy.linalg import null_space
from sympy import N as sN
from sympy.physics.wigner import gaunt

from geovac.shibuya_wulfman import _hydrogenic_poly_coeffs

NMAX = 4
STATES = [(n, l, m) for n in range(1, NMAX + 1) for l in range(n) for m in range(-l, l + 1)]
IDX = {s: i for i, s in enumerate(STATES)}
DIM = len(STATES)


def _radial_r3(n1: int, l1: int, n2: int, l2: int) -> float:
    c1, a1 = _hydrogenic_poly_coeffs(1.0, n1, l1)
    c2, a2 = _hydrogenic_poly_coeffs(1.0, n2, l2)
    tot = 0.0
    for i, ci in enumerate(c1):
        for j, cj in enumerate(c2):
            p = i + j + 3
            tot += ci * cj * factorial(p) / (a1 + a2) ** (p + 1)
    return tot


def _ang(l1: int, m1: int, l2: int, m2: int, mu: int) -> float:
    return float(sN((-1) ** m1 * gaunt(l1, 1, l2, -m1, mu, m2))) * sqrt(4 * np.pi / 3)


def generators() -> Tuple[List[np.ndarray], List[np.ndarray]]:
    """L (ladder algebra) and A (Pauli shell identity), as in tests/test_atlas_so4_commutant.py."""
    L = [np.zeros((DIM, DIM), complex) for _ in range(3)]
    A = [np.zeros((DIM, DIM), complex) for _ in range(3)]
    for (n, l, m) in STATES:
        i = IDX[(n, l, m)]
        L[2][i, i] = m
        if m + 1 <= l:
            c = sqrt(l * (l + 1) - m * (m + 1))
            L[0][IDX[(n, l, m + 1)], i] += c / 2
            L[1][IDX[(n, l, m + 1)], i] += c / (2j)
        if m - 1 >= -l:
            c = sqrt(l * (l + 1) - m * (m - 1))
            L[0][IDX[(n, l, m - 1)], i] += c / 2
            L[1][IDX[(n, l, m - 1)], i] += -c / (2j)
    for n in range(1, NMAX + 1):
        sh = [s for s in STATES if s[0] == n]
        ids = [IDX[s] for s in sh]
        k = len(sh)
        X, Y, Z = (np.zeros((k, k), complex) for _ in range(3))
        for i, (_, l1, m1) in enumerate(sh):
            for j, (_, l2, m2) in enumerate(sh):
                rad = _radial_r3(n, l1, n, l2)
                yp, ym = _ang(l1, m1, l2, m2, 1), _ang(l1, m1, l2, m2, -1)
                Z[i, j] = rad * _ang(l1, m1, l2, m2, 0)
                X[i, j] = rad * (ym - yp) / sqrt(2)
                Y[i, j] = rad * 1j * (ym + yp) / sqrt(2)
        for a, M in enumerate((X, Y, Z)):
            A[a][np.ix_(ids, ids)] = -(2.0 / (3.0 * n)) * M
    return L, A


def comm(P: np.ndarray, Q: np.ndarray) -> np.ndarray:
    return P @ Q - Q @ P


def eps(i: int, j: int, k: int) -> int:
    return int(np.sign((j - i) * (k - i) * (k - j)))


def su2_defect(G: List[np.ndarray]) -> float:
    return max(np.abs(comm(G[i], G[j]) - 1j * sum(eps(i, j, k) * G[k] for k in range(3))).max()
               for i in range(3) for j in range(3))


def door24_operator(R: float = 0.05, npts: int = 4001) -> np.ndarray:
    """Finite-nucleus correction V_sphere + Z/r (Z = 1), the guard's operator; central, so (l, m)-diagonal."""
    r = np.linspace(1e-6, R, npts)
    dV = -(3 / (2 * R) - r * r / (2 * R ** 3)) + 1 / r
    V = np.zeros((DIM, DIM), complex)
    for (n1, l1, m1) in STATES:
        for (n2, l2, m2) in STATES:
            if (l1, m1) != (l2, m2):
                continue
            c1, a1 = _hydrogenic_poly_coeffs(1.0, n1, l1)
            c2, a2 = _hydrogenic_poly_coeffs(1.0, n2, l2)
            R1 = np.exp(-a1 * r) * np.polyval(c1[::-1], r)
            R2 = np.exp(-a2 * r) * np.polyval(c2[::-1], r)
            V[IDX[(n1, l1, m1)], IDX[(n2, l2, m2)]] = np.trapezoid(R1 * R2 * dV * r * r, r)
    return V


def commutant_dim(V: np.ndarray, gens: List[np.ndarray], tol: float = 1e-10) -> Tuple[int, np.ndarray]:
    M = np.array([comm(V, G).ravel() for G in gens]).T
    s = np.linalg.svd(M, compute_uv=False)
    rel = s / (np.linalg.norm(V) * max(np.linalg.norm(G) for G in gens))
    return int(np.sum(rel < tol)), rel


def invariant_count(gens: List[np.ndarray], ids: List[int]) -> int:
    M = np.vstack([G[np.ix_(ids, ids)] for G in gens])
    return null_space(M, rcond=1e-10).shape[1]


def main() -> None:
    L, A = generators()
    Jp = [(L[a] + A[a]) / 2 for a in range(3)]
    Jm = [(L[a] - A[a]) / 2 for a in range(3)]
    print(f"basis: hydrogenic Z=1, n <= {NMAX}, dim {DIM}")
    print("1. algebra")
    print(f"   su(2) defect  L: {su2_defect(L):.1e}  J+: {su2_defect(Jp):.1e}  J-: {su2_defect(Jm):.1e}")
    print(f"   max |[J+_a, J-_b]|: {max(np.abs(comm(Jp[a], Jm[b])).max() for a in range(3) for b in range(3)):.1e}")
    n_diag = np.diag([(n * n - 1) / 4 for (n, l, m) in STATES])
    print(f"   |J+^2 - (n^2-1)/4|: {np.abs(sum(G @ G for G in Jp) - n_diag).max():.1e}"
          f"   |J-^2 - (n^2-1)/4|: {np.abs(sum(G @ G for G in Jm) - n_diag).max():.1e}")

    V = door24_operator()
    print("2. commutant of the door-24 correction (uniform sphere, R = 0.05)")
    for name, gens in (("so(4) = span(L, A)", L + A), ("so(4) = span(J+, J-)", Jp + Jm),
                       ("su(2)_+ = span(J+)", Jp), ("su(2)_- = span(J-)", Jm), ("span(L)", L)):
        d, rel = commutant_dim(V, gens)
        print(f"   {name:22s} dim {d}   relative singular values {np.array2string(np.sort(rel), precision=3)}")

    print("3. relative commutators ||[V, X]|| / ||V||")
    nV = np.linalg.norm(V)
    for name, G in (("L", L), ("A", A), ("J+", Jp), ("J-", Jm)):
        vals = [np.linalg.norm(comm(V, G[a])) / nV for a in range(3)]
        print(f"   {name:3s} x,y,z: " + "  ".join(f"{v:.3e}" for v in vals))
    hopf = L[2] + A[2]
    print(f"   Hopf generator L_z + A_z = 2 J+_z: {np.linalg.norm(comm(V, hopf)) / nV:.3e}")

    print("4. invariant vectors per shell (label shadow of fixed points)")
    for n in range(1, NMAX + 1):
        ids = [IDX[s] for s in STATES if s[0] == n]
        print(f"   n={n}: diagonal SO(3) (L): {invariant_count(L, ids)}   SU(2)_+ (J+): {invariant_count(Jp, ids)}"
              f"   SU(2)_- (J-): {invariant_count(Jm, ids)}   shell dim {len(ids)}")


if __name__ == "__main__":
    main()
