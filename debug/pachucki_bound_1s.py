"""1s exchange via Pachucki's ODE: exact closed form, module rank, numeric check.

Run:  python debug/pachucki_bound_1s.py A B      (A < B rationals, default 1 2)
Writes debug/data/pachucki_bound_1s_<A>_<B>.json  (closed form + ranks + numerics).
"""
from __future__ import annotations

import itertools
import json
import sys
import time

import mpmath as mp
import sympy as sp

sys.path.insert(0, "debug")
import pachucki_bound_core as C  # noqa: E402
from pachucki_bound_core import r, LC  # noqa: E402

a = sp.Rational(sys.argv[1]) if len(sys.argv) > 1 else sp.Integer(1)
b = sp.Rational(sys.argv[2]) if len(sys.argv) > 2 else sp.Integer(2)
assert 0 < a < b
t0 = time.time()
F, p2, lnabs = C.pachucki_F_and_p2()
sub = C.theta0(a, b)
lnval = sp.simplify(lnabs.subs(sub))           # = ln((a+b)/(b-a))
print("ln-constant at theta0:", lnval)
lnc = (lnval,)

# ---- F^{(-1)} of Pachucki Eq. (63) (u=a, w=b) and its check d/dr F^{(-1)} = F(theta0)
u, w = a, b
Lw = sp.log(abs((w - u) / (w + u)))           # = -lnval
Fm1 = (1 / (2 * (u**2 - w**2))) * (
    (sp.exp(2 * r * w) - sp.exp(2 * r * u)) * sp.Ei(-2 * r * (u + w))
    - sp.exp(-2 * r * w) * (sp.Ei(2 * r * (w - u)) - 2 * sp.Ei(r * (w - u)) + Lw)
    + sp.exp(-2 * r * u) * (sp.Ei(2 * r * (u - w)) - 2 * sp.Ei(r * (u - w)) + Lw))
FM1 = C.to_func(sp.expand(Fm1).subs(sp.log(sp.Abs((w - u) / (w + u))), -lnval).subs(Lw, -lnval), lnc)
C.FM1.update(FM1)
F0 = C.to_func(F.subs(sub), lnc)
ok_63 = C.fequal(C.fdiff(FM1), F0)
print("Eq.(63) is the antiderivative of Eq.(31) at theta0:", ok_63)

# ---- all subset derivatives
alphas = [al for al in itertools.product((0, 1), repeat=4)]
D = C.multi_derivs(F, p2, alphas, sub)
Fs = {al: C.to_func(D[al][0], lnc) for al in alphas}
P2 = {al: D[al][1] for al in alphas}
print("d_U p^2 at theta0:", {"".join(map(str, k)): str(v) for k, v in P2.items() if v != 0})

keys = set()
for al in alphas:
    keys |= C.keys_closure(Fs[al])
keys = sorted(k for k in keys if not (k[0] == "E" and k[1] == 0))
print("explicit keys:", keys)
ans_keys = keys + [("f",)]

FREE = {}
fS = {(0, 0, 0, 0): {("f",): {0: sp.Integer(1)}}}
for al in sorted(alphas, key=sum):
    if sum(al) == 0:
        continue
    src = C.fscale(Fs[al], -1)
    for be in C.sub_multi(al):
        U = tuple(x - y for x, y in zip(al, be))
        if sum(U) == 0:
            continue
        c = C.binom_multi(al, U) * P2[U]
        if c != 0:
            src = C.fadd(src, C.fscale(fS[be], c, 1))
    sol, free = C.solve_L0(src, ans_keys, -6, 6)
    fS[al] = sol
    FREE[al] = len(free)
    print("solved f_S for S =", al, " keys:", sorted(sol.keys(), key=str), " (%.0fs)" % (time.time() - t0))

f1234 = fS[(1, 1, 1, 1)]
Kfun = C.fscale(f1234, 16 * a**3 * b**3, -1)       # K = 16 a^3 b^3 f_1234 / R


# ---- rank of the D-module generated by K over Q(R): coordinates of K, K', ..., K^(n)
def coords(A, keylist):
    return [sum(c * r**p for p, c in A.get(k, {}).items()) for k in keylist]


closure = sorted(C.keys_closure(Kfun), key=str)
rows, cur = [], Kfun
for i in range(len(closure) + 1):
    rows.append(coords(cur, closure))
    cur = C.fdiff(cur)
Mx = sp.Matrix(rows)
# exact rank over Q(R, LC): fraction-free over the field of fractions
from sympy.polys.matrices import DomainMatrix  # noqa: E402
dom = sp.QQ.frac_field(r, LC)
rank = DomainMatrix.from_Matrix(Mx).convert_to(dom).rank()
print("closure keys of K:", closure, " count", len(closure))
print("rank of span{K, K', ...} over Q(R, LC):", rank)

# ---- numerics: evaluate K at R = 1.4 to high precision
mp.mp.dps = 60
lcnum = mp.log(mp.mpf(sp.Rational(a + b, b - a).p) / sp.Rational(a + b, b - a).q)


def ev_key(k, x):
    if k[0] == "E":
        return mp.exp(mp.mpf(k[1].p) / k[1].q * x)
    if k[0] == "Ei":
        lam, mu = (mp.mpf(v.p) / v.q for v in (k[1], k[2]))
        return mp.exp(lam * x) * mp.ei(mu * x)
    raise KeyError


def ev(A, x, f0=None):
    s = mp.mpf(0)
    for k, d in A.items():
        bk = f0 if k[0] == "f" else ev_key(k, x)
        for p, c in d.items():
            cc = sp.Poly(c, LC)
            cv = sum(mp.mpf(sp.Rational(co).p) / sp.Rational(co).q * lcnum**m[0]
                     for m, co in zip(cc.monoms(), cc.coeffs()))
            s += cv * x**p * bk
    return s


def f0_num(x):
    return mp.quad(lambda s: ev(FM1, s) / s, [x, x + 2, x + 10, mp.inf])


out = {"pair": [str(a), str(b)], "eq63_antiderivative_check": ok_63,
       "lnconst": str(lnval), "dU_p2": {"".join(map(str, k)): str(v) for k, v in P2.items() if v != 0},
       "free_ansatz_columns": {"".join(map(str, k)): v for k, v in FREE.items()},
       "K_closure_keys": [str(k) for k in closure], "K_rank": int(rank)}
for Rv in ("1.4", "3.015"):
    x = mp.mpf(Rv)
    val = ev(Kfun, x, f0_num(x))
    out["K_" + Rv] = mp.nstr(val, 50)
    print("K(%s) =" % Rv, mp.nstr(val, 50))
out["K_closed_form"] = {str(k): {str(p): str(c) for p, c in d.items()} for k, d in Kfun.items()}
out["time_s"] = round(time.time() - t0, 1)
tag = f"{str(a).replace('/', '_')}_{str(b).replace('/', '_')}"
json.dump(out, open(f"debug/data/pachucki_bound_1s_{tag}.json", "w"), indent=1)
print("done %.0fs" % (time.time() - t0))
